export type RouteAccess =
  | { kind: 'public' }
  | { kind: 'authenticated' }
  | { kind: 'permission'; permission: Permission; ownAllowed?: boolean };

export interface RouteContract {
  id: string;
  method: 'get' | 'post' | 'patch' | 'delete';
  path: string;
  summary: string;
  tags: string[];
  access: RouteAccess;
  scope: 'none' | 'org' | 'workspace' | 'project' | 'own_or_workspace';
  idempotent: boolean;
  rateLimitClass: 'public' | 'auth' | 'read' | 'write';
  paramsSchema?: z.ZodTypeAny;
  querySchema?: z.ZodTypeAny;
  bodySchema?: z.ZodTypeAny;
  responseSchema?: z.ZodTypeAny;
  successStatus: 200 | 201 | 202 | 204 | 302;
}

